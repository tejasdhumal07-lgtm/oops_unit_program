#include <iostream> // Header file for input and output stream operations
using namespace std; // Use standard namespace to avoid std:: prefix

int main() { // Main function: entry point of the C++ program
    int roll = 101; // Declare integer variable 'roll' and initialize it to 101
    char grade = 'A'; // Declare character variable 'grade' and initialize it to 'A'
    float fee = 12500.50; // Declare floating-point variable 'fee' and initialize it to 12500.50
    cout << "Roll No: " << roll << endl; // Output roll number with label to console and move to next line
    cout << "Grade: " << grade << endl; // Output grade with label to console and move to next line
    cout << "Fee: " << fee << endl; // Output fee with label to console and move to next line
    return 0; // Return 0 to OS indicating successful program execution
} // End of main function
